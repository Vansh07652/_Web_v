const clamp = (value, low, high) => Math.min(high, Math.max(low, value));

const sectionCharacterCount = (sections) => Object.values(sections ?? {})
  .filter((value) => typeof value === "string" && value.trim().length > 0)
  .reduce((total, value) => total + value.length, 0);

const topicReferenceHosts = (sections) => {
  const hosts = new Set();
  for (const reference of sections?.references ?? []) {
    const host = referenceHost(reference?.url);
    if (host) hosts.add(host);
  }
  return [...hosts].sort();
};

const modalDifficulty = (counts) => {
  const total = [...counts.values()].reduce((sum, count) => sum + count, 0);
  if (total < minimumDifficultySample) return undefined;
  const [best] = [...counts.entries()].sort((left, right) => right[1] - left[1]
    || questionDifficultyRank.indexOf(left[0]) - questionDifficultyRank.indexOf(right[0]));
  return difficultyByQuestionDifficulty[best[0]];
};

export const buildTopicMetadata = () => {
  const corpus = readCurriculumCorpus();
  const mappedQuestionCount = new Map();
  const citationReviewCount = new Map();
  const difficultyCounts = new Map();
  const coMappings = new Map();
  const bump = (map, key) => map.set(key, (map.get(key) ?? 0) + 1);

  for (const subject of corpus.subjects) {
    for (const question of subject.questions) {
      const ids = mappedTopicIds(question);
      for (const id of ids) {
        bump(mappedQuestionCount, id);
        if (question.citationReviewRequired === true) bump(citationReviewCount, id);
        if (question.mappingScope === "exact" && difficultyByQuestionDifficulty[question.difficulty]) {
          if (!difficultyCounts.has(id)) difficultyCounts.set(id, new Map());
          bump(difficultyCounts.get(id), question.difficulty);
        }
      }
      if (ids.length < 2) continue;
      for (const id of ids) {
        if (!coMappings.has(id)) coMappings.set(id, new Map());
        const neighbours = coMappings.get(id);
        for (const other of ids) if (other !== id) bump(neighbours, other);
      }
    }
  }

  const topics = {};
  for (const subject of corpus.subjects) {
    const programs = programsByCategory[subject.summary.category];
    for (const topic of subject.topics) {
      const { bundle } = topic;
      const characters = sectionCharacterCount(bundle.sections);
      const questionCount = mappedQuestionCount.get(bundle.id) ?? 0;
      const contentStatus = contentStatusByTopicStatus[bundle.status];
      const sourceIds = [...new Set([
        ...(bundle.provenance?.sourceCollection ? [`collection:${bundle.provenance.sourceCollection}`] : []),
        ...topicReferenceHosts(bundle.sections).map((host) => `reference-host:${host}`),
      ])].sort();
      const entry = {
        programs: [...(programs ?? [])],
        estimatedStudyMinutes: clamp(Math.round(characters / readingCharactersPerMinute + questionCount), minimumStudyMinutes, maximumStudyMinutes),
        sectionCharacterCount: characters,
        exactQuestionCount: questionCount,
        citationReviewQuestionCount: citationReviewCount.get(bundle.id) ?? 0,
        contentStatus,
        sourceIds,
        publish: contentStatus === "source-grounded",
      };
      const difficulty = difficultyCounts.has(bundle.id) ? modalDifficulty(difficultyCounts.get(bundle.id)) : undefined;
      if (difficulty) entry.difficulty = difficulty;
      const neighbours = coMappings.get(bundle.id);
      if (neighbours && neighbours.size > 0) {
        entry.relatedTopics = [...neighbours.entries()]
          .sort((left, right) => right[1] - left[1] || left[0].localeCompare(right[0]))
          .slice(0, maximumRelatedTopics)
          .map(([id]) => id);
      }
      topics[bundle.id] = entry;
    }
  }

  return {
    schemaVersion: "2.0.0",
    generatedOn: corpus.catalog.generatedOn,
    generatedBy: "scripts/build-topic-metadata.mjs",
    notes,
    derivationRules,
    topics,
  };
};


/** Fixed subject-category mapping. This is a category-level statement, never a per-topic judgement. */
export const programsByCategory = {
  "pre-health-core": ["pre-nursing", "nursing", "premed", "healthcare"],
  "healthcare-foundations": ["pre-nursing", "nursing", "healthcare"],
  pathophysiology: ["nursing", "healthcare"],
  "allied-health": ["healthcare"],
};

/** Topic status (as generated by the importers) -> published content status. */
export const contentStatusByTopicStatus = {
  final: "source-grounded",
  final_requires_citation_review: "needs-medical-review",
  available: "draft",
};

/** Question difficulty -> learner-facing difficulty. `unknown` and absent values are not mappable. */
export const difficultyByQuestionDifficulty = {
  foundational: "beginner",
  intermediate: "intermediate",
  advanced: "advanced",
};

/**
 * Wire-format legends. These list every *legal* enum value, not just the values
 * this corpus happens to emit, so an integer code never shifts meaning when the
 * content changes. They are written into the file as `tables.contentStatus` and
 * `tables.difficulty`, and `src/lib/content/metadata.ts` reads the codes from
 * there rather than hard-coding them.
 */
export const contentStatusCodes = ["source-grounded", "medically-reviewed", "needs-medical-review", "draft", "archived"];
export const difficultyCodes = ["beginner", "intermediate", "advanced"];

const questionDifficultyRank = ["foundational", "intermediate", "advanced"];
const readingCharactersPerMinute = 900;
const minimumStudyMinutes = 2;
const maximumStudyMinutes = 90;
const minimumDifficultySample = 5;
const maximumRelatedTopics = 6;


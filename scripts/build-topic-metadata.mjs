/** `topic:<subject>:<unit>:<slug>`. The slug may hold colons; the first three segments may not. */
const splitTopicId = (topicId) => {
  const parts = topicId.split(":");
  const [prefix, subject, unit] = parts;
  const slug = parts.slice(3).join(":");
  if (prefix !== "topic" || parts.length < 4 || !subject || !unit || !slug) {
    throw new Error(`Topic id ${topicId} is not of the form topic:<subject>:<unit>:<slug> and cannot be interned`);
  }
  return { subject, unit, slug };
};

/** Interns the derived index into the wire format. Lossless: decodeTopicMetadata reverses it exactly. */
export const encodeTopicMetadata = (index) => {
  const ids = Object.keys(index.topics);
  const ordinalById = new Map(ids.map((id, ordinal) => [id, ordinal]));
  const sources = [...new Set(ids.flatMap((id) => index.topics[id].sourceIds))].sort();
  const sourceCode = new Map(sources.map((sourceId, code) => [sourceId, code]));
  const programKeys = [...new Set(ids.map((id) => JSON.stringify(index.topics[id].programs)))].sort();
  const programCode = new Map(programKeys.map((key, code) => [key, code]));

  const subjects = [];
  for (const topicId of ids) {
    const entry = index.topics[topicId];
    const { subject, unit, slug } = splitTopicId(topicId);
    if (entry.publish !== (entry.contentStatus === "source-grounded")) {
      throw new Error(`${topicId}: publish disagrees with contentStatus, so it cannot be derived at read time`);
    }
    const contentStatus = contentStatusCodes.indexOf(entry.contentStatus);
    if (contentStatus < 0) throw new Error(`${topicId}: contentStatus ${entry.contentStatus} is not a legal value`);
    const difficulty = entry.difficulty === undefined ? -1 : difficultyCodes.indexOf(entry.difficulty);
    if (difficulty < 0 && entry.difficulty !== undefined) throw new Error(`${topicId}: difficulty ${entry.difficulty} is not a legal value`);
    const row = [
      slug,
      programCode.get(JSON.stringify(entry.programs)),
      entry.estimatedStudyMinutes,
      entry.sectionCharacterCount,
      entry.exactQuestionCount,
      entry.citationReviewQuestionCount,
      contentStatus,
      entry.sourceIds.map((sourceId) => sourceCode.get(sourceId)),
    ];
    if (entry.relatedTopics) {
      row.push(difficulty, entry.relatedTopics.map((relatedId) => {
        const ordinal = ordinalById.get(relatedId);
        if (ordinal === undefined) throw new Error(`${topicId}: relatedTopics entry ${relatedId} has no entry of its own to point at`);
        return ordinal;
      }));
    } else if (difficulty >= 0) row.push(difficulty);

    let subjectGroup = subjects.at(-1);
    if (!subjectGroup || subjectGroup[0] !== subject) {
      subjectGroup = [subject, []];
      subjects.push(subjectGroup);
    }
    let unitGroup = subjectGroup[1].at(-1);
    if (!unitGroup || unitGroup[0] !== unit) {
      unitGroup = [unit, []];
      subjectGroup[1].push(unitGroup);
    }
    unitGroup[1].push(row);
  }

  return {
    schemaVersion: index.schemaVersion,
    generatedOn: index.generatedOn,
    generatedBy: index.generatedBy,
    encoding: encodingLegend,
    notes: index.notes,
    derivationRules: index.derivationRules,
    tables: {
      sources,
      programs: programKeys.map((key) => JSON.parse(key)),
      contentStatus: contentStatusCodes,
      difficulty: difficultyCodes,
    },
    topics: subjects,
  };
};

/**
 * The inverse of encodeTopicMetadata: the wire format back to the derived index
 * every consumer sees. src/lib/content/metadata.ts carries the same walk in
 * TypeScript, because a Node script cannot import it; change them together.
 */
export const decodeTopicMetadata = (document) => {
  const { sources, programs, contentStatus, difficulty } = document.tables ?? {};
  const ids = [];
  const rows = [];
  for (const [subject, units] of document.topics ?? []) {
    for (const [unit, entries] of units) {
      for (const row of entries) {
        ids.push(`topic:${subject}:${unit}:${row[0]}`);
        rows.push(row);
      }
    }
  }
  const topics = {};
  rows.forEach((row, ordinal) => {
    const status = contentStatus[row[6]];
    const entry = {
      programs: [...programs[row[1]]],
      estimatedStudyMinutes: row[2],
      sectionCharacterCount: row[3],
      exactQuestionCount: row[4],
      citationReviewQuestionCount: row[5],
      contentStatus: status,
      sourceIds: row[7].map((code) => sources[code]),
      publish: status === "source-grounded",
    };
    if (row[8] !== undefined && row[8] >= 0) entry.difficulty = difficulty[row[8]];
    if (row[9] !== undefined) entry.relatedTopics = row[9].map((relatedOrdinal) => ids[relatedOrdinal]);
    topics[ids[ordinal]] = entry;
  });
  return {
    schemaVersion: document.schemaVersion,
    generatedOn: document.generatedOn,
    generatedBy: document.generatedBy,
    notes: document.notes,
    derivationRules: document.derivationRules,
    topics,
  };
};

/**
 * Pretty-prints down to `depth` and emits everything below it on one line. The
 * header and the table names stay reviewable; the 1409-entry payload does not
 * pay for indentation it has no reader for.
 */
const serializeAtDepth = (value, depth, indent) => {
  if (depth <= 0 || value === null || typeof value !== "object") return JSON.stringify(value);
  const inner = `${indent}  `;
  const body = Array.isArray(value)
    ? value.map((item) => `${inner}${serializeAtDepth(item, depth - 1, inner)}`)
    : Object.entries(value).map(([key, item]) => `${inner}${JSON.stringify(key)}: ${serializeAtDepth(item, depth - 1, inner)}`);
  const [open, close] = Array.isArray(value) ? ["[", "]"] : ["{", "}"];
  if (body.length === 0) return `${open}${close}`;
  return `${open}\n${body.join(",\n")}\n${indent}${close}`;
};

/** Canonical on-disk encoding for this sidecar: readable header, interned payload, trailing newline. */
export const serializeTopicMetadataDocument = (document) => `${serializeAtDepth(document, 2, "")}\n`;

export const serializeTopicMetadata = () => serializeTopicMetadataDocument(encodeTopicMetadata(buildTopicMetadata()));

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const metadata = buildTopicMetadata();
  const serialized = serializeTopicMetadataDocument(encodeTopicMetadata(metadata));
  writeGeneratedFile(outputFile, serialized);
  const entries = Object.values(metadata.topics);
  const withDifficulty = entries.filter((entry) => entry.difficulty).length;
  const withRelated = entries.filter((entry) => entry.relatedTopics).length;
  const published = entries.filter((entry) => entry.publish).length;
  console.log(`Wrote ${path.relative(repositoryRoot, outputFile)} (${Buffer.byteLength(serialized)} bytes)`);
  console.log(`${entries.length} topics; ${withDifficulty} with a derived difficulty; ${withRelated} with relatedTopics; ${published} publishable.`);
  console.log(`Deliberately omitted fields: ${notes.length} documented in the file's notes array.`);
}

